"""Regenerate reference-cases.ts using Python Decimal, independent of the TS engine.

Run: python3 src/lib/financing/__tests__/generate_references.py
Uses the conventional PMT formula, 100 decimal digits and ROUND_HALF_UP.
Only checkpoints/totals are stored; the complete schedule is calculated here.
"""
from decimal import Decimal as D, ROUND_HALF_UP, localcontext
import json
from pathlib import Path


def reference(price, down, rate, months, currency="AMD"):
    with localcontext() as ctx:
        ctx.prec = 100
        rounded = lambda value: value.quantize(D(1), rounding=ROUND_HALF_UP)
        down_amount = rounded(D(price) * D(str(down)) / 100)
        principal = D(price) - down_amount
        monthly_rate = D(str(rate)) / 1200
        monthly = rounded(
            principal / months if monthly_rate == 0 else
            principal * monthly_rate / (1 - (1 + monthly_rate) ** (-months))
        )
        balance = principal
        total_interest = D(0)
        total_repayment = D(0)
        rows = []
        for month in range(1, months + 1):
            interest = rounded(balance * monthly_rate)
            payment = balance + interest if month == months else min(monthly, balance + interest)
            paid_principal = payment - interest
            remaining = balance - paid_principal
            rows.append(dict(month=month, openingBalance=int(balance), scheduledPayment=int(payment),
                             principalPaid=int(paid_principal), interestPaid=int(interest), remainingBalance=int(remaining)))
            balance = remaining
            total_interest += interest
            total_repayment += payment
        return dict(
            input=dict(currency=currency, financingType="mortgage", apartmentPrice=price, downPaymentPercent=down,
                       annualInterestRatePercent=rate, durationMonths=months),
            expected=dict(downPaymentAmount=int(down_amount), financedPrincipal=int(principal),
                          regularMonthlyPayment=int(monthly), totalInterest=int(total_interest),
                          totalFinancedRepayment=int(total_repayment),
                          totalCostIncludingDownPayment=int(down_amount + total_repayment)),
            checkpoints=[rows[i] for i in sorted(set([0, min(1, months-1), months//2, months-1]))],
        )


cases = [reference(*case) for case in [
    (50_000_000, 20, 12, 240),
    (64_999_999, 12.5, 9.5, 180),
    (120_000_000, 30, 7.25, 360),
    (1_000_000_000_000, 0, 100, 600),
    (200, 5, 12, 3),
    (1_000_001, 33.333333, 0, 7),
    (15_000_000, 0, 1e-12, 480),
    (1_250, 20, 12, 3),
    (1, 0, 100, 1),
    (150_000, 20, 9.5, 240, "USD"),
    (250_000, 12.5, 6.75, 360, "USD"),
    (1_003, 10.5, 0, 7, "USD"),
]]
Path(__file__).with_name("reference-cases.ts").write_text(
    "// Generated by generate_references.py using independent Python Decimal arithmetic.\n"
    "export const referenceCases = " + json.dumps(cases, indent=2) + " as const;\n"
)
